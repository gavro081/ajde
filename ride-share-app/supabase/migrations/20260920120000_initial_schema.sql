create function public.recalculate_ride_seats(target_ride_id uuid)
returns void
language plpgsql
set search_path = ''
as $$
declare
  capacity smallint;
  accepted_seats integer;
  remaining_seats integer;
begin
  select seats_total
  into capacity
  from public.rides
  where id = target_ride_id
  for update;

  if capacity is null then
    return;
  end if;

  select coalesce(sum(seats), 0)
  into accepted_seats
  from public.bookings
  where ride_id = target_ride_id
    and status = 'accepted';

  remaining_seats := capacity - accepted_seats;

  if remaining_seats < 0 then
    raise exception 'Ride % does not have enough available seats', target_ride_id
      using errcode = '23514';
  end if;

  update public.rides
  set
    seats_available = remaining_seats,
    status = case
      when remaining_seats = 0 and status = 'published' then 'full'::public.ride_status
      when remaining_seats > 0 and status = 'full' then 'published'::public.ride_status
      else status
    end
  where id = target_ride_id;
end;
$$;

create function public.sync_ride_seats()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform public.recalculate_ride_seats(
    case when tg_op = 'DELETE' then old.ride_id else new.ride_id end
  );

  if tg_op = 'DELETE' then
    return old;
  end if;

  return new;
end;
$$;

create function public.guard_booking_identity()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.ride_id <> old.ride_id or new.passenger_id <> old.passenger_id then
    raise exception 'A booking ride and passenger cannot be changed'
      using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger bookings_guard_identity
before update on public.bookings
for each row execute function public.guard_booking_identity();

create trigger bookings_sync_ride_seats
after insert or update or delete on public.bookings
for each row execute function public.sync_ride_seats();

create function public.guard_ride_capacity_change()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  accepted_seats integer;
begin
  if new.seats_total = old.seats_total then
    return new;
  end if;

  select coalesce(sum(seats), 0)
  into accepted_seats
  from public.bookings
  where ride_id = new.id
    and status = 'accepted';

  if new.seats_total < accepted_seats then
    raise exception 'Ride capacity cannot be lower than accepted seats (%)', accepted_seats
      using errcode = '23514';
  end if;

  new.seats_available := new.seats_total - accepted_seats;
  return new;
end;
$$;

create trigger rides_guard_capacity_change
before update of seats_total on public.rides
for each row execute function public.guard_ride_capacity_change();

